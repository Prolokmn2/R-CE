-- RemoteSpy: captures FireServer / InvokeServer / FireAllClients / FireClient traffic
-- Inspired by DEX++ and Ketamine's approach: intercept __namecall + hookfunction on RemoteEvent/Function prototypes
return function(RCE)
	local E = RCE.require("src/core/Env.lua")
	local U = RCE.require("src/core/Util.lua")
	local Registry = RCE.require("src/core/Registry.lua")

	local RS = {
		log = {},
		MAX = 2000,
		listeners = {},
		flags = { enabled = false, paused = false, filterEnabled = true },
		filter = { whitelist = {}, blacklist = {} },
	}

	local shared = Registry.get("remotespy_shared")
	if type(shared) ~= "table" then
		shared = {}
		Registry.set("remotespy_shared", shared)
	end

	local nextId = 0
	local function push(direction, remote, method, args, ret)
		if RS.flags.paused then return end
		nextId += 1
		local path = U.pathOf(remote)
		-- filter check
		if RS.flags.filterEnabled then
			for _, pat in ipairs(RS.filter.blacklist) do
				if path:lower():find(pat:lower(), 1, true) then return end
			end
			if #RS.filter.whitelist > 0 then
				local ok = false
				for _, pat in ipairs(RS.filter.whitelist) do
					if path:lower():find(pat:lower(), 1, true) then ok = true; break end
				end
				if not ok then return end
			end
		end
		local e = {
			id = nextId,
			t = os.clock(),
			direction = direction,
			remote = remote,
			path = path,
			method = method,
			args = args,
			ret = ret,
		}
		RS.log[#RS.log + 1] = e
		if #RS.log > RS.MAX then table.remove(RS.log, 1) end
		for _, f in ipairs(RS.listeners) do pcall(f, e) end
	end

	function RS.onLog(f) table.insert(RS.listeners, f) end
	function RS.clear() table.clear(RS.log) end

	-- Build a pretty summary of one log entry
	function RS.format(e)
		local lines = {
			("Remote : %s"):format(e.path),
			("Class  : %s"):format(e.remote.ClassName),
			("Method : %s"):format(e.method),
			("Dir    : %s"):format(e.direction),
			("Time   : %.4f"):format(e.t),
			("Args   : %d"):format(e.args.n),
		}
		for i = 1, e.args.n do
			lines[#lines + 1] = ("  [%d] %s = %s"):format(i, typeof(e.args[i]), U.trunc(U.ser(e.args[i]), 200))
		end
		if e.ret then
			lines[#lines + 1] = ("Returns: %d"):format(e.ret.n)
			for i = 1, e.ret.n do
				lines[#lines + 1] = ("  [%d] %s = %s"):format(i, typeof(e.ret[i]), U.trunc(U.ser(e.ret[i]), 200))
			end
		end
		return lines
	end

	-- Generate a re-fire script for the selected remote call
	function RS.generateScript(e)
		local lines = {
			"-- Auto-generated by R-CE Remote Spy",
			("local remote = game:GetService(\"Players\").LocalPlayer -- adjust path"),
			("-- Path: %s"):format(e.path),
			("local r = game"),
		}
		local parts = {}
		for seg in e.path:gmatch("[^%.]+") do parts[#parts + 1] = seg end
		local access = "game"
		for i, seg in ipairs(parts) do
			if i == 1 then
				local ok, svc = pcall(function() return game:GetService(seg) end)
				if ok and svc then
					access = ('game:GetService("%s")'):format(seg)
				else
					access = ('game["%s"]'):format(seg)
				end
			elseif i > 1 then
				access = access .. ('.%s'):format(seg)
			end
		end
		lines[#lines + 1] = ("local remote = %s"):format(access)
		local argParts = {}
		for i = 1, e.args.n do
			argParts[#argParts + 1] = U.ser(e.args[i], 0)
		end
		if e.method == "FireServer" then
			lines[#lines + 1] = ("remote:FireServer(%s)"):format(table.concat(argParts, ", "))
		elseif e.method == "InvokeServer" then
			lines[#lines + 1] = ("local result = remote:InvokeServer(%s)"):format(table.concat(argParts, ", "))
			lines[#lines + 1] = "print(result)"
		end
		return lines
	end

	local METHODS = { FireServer = "C→S", InvokeServer = "C→S invoke", FireAllClients = "S→all", FireClient = "S→C" }

	function RS.install()
		if not (E.hookmetamethod and E.getnamecallmethod) then
			return false, "hookmetamethod / getnamecallmethod missing"
		end
		shared.rspySink = function(remote, method, args, ret)
			if RS.flags.enabled then
				task.defer(push, METHODS[method] or method, remote, method, args, ret)
			end
		end
		if shared.rspyInstalled then return true end
		local old
		local ok, err = pcall(function()
			old = E.hookmetamethod(game, "__namecall", E.newcclosure(function(self, ...)
				local method = E.getnamecallmethod()
				local sink = shared.rspySink
				if sink and METHODS[method] and typeof(self) == "Instance"
					and (self.ClassName == "RemoteEvent" or self.ClassName == "RemoteFunction"
						or self.ClassName == "BindableEvent" or self.ClassName == "BindableFunction") then
					if not (E.checkcaller and E.checkcaller()) then
						local packed = table.pack(...)
						if method == "InvokeServer" then
							local rets = table.pack(old(self, ...))
							sink(self, method, packed, rets)
							return table.unpack(rets, 1, rets.n)
						else
							sink(self, method, packed, nil)
						end
					end
				end
				if E.setnamecallmethod then E.setnamecallmethod(method) end
				return old(self, ...)
			end))
		end)
		if not ok then return false, tostring(err) end
		shared.rspyInstalled = true
		return true
	end

	RCE.OnUnload(function()
		RS.flags.enabled = false
		shared.rspySink = nil
	end)

	return RS
end
